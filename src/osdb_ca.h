/*
 *   The root the session archive trusts: ISRG Root X2, and nothing else.
 *
 *   The endpoint is published through the same central proxy as npn, hermes and
 *   chat.d4rkn3t.de, and that proxy serves Let's Encrypt certificates. The chain
 *   it presents is
 *
 *       osdb.d4rkn3t.de  <-  YE1  <-  Root YE  <-  ISRG Root X2  <-  ISRG Root X1
 *
 *   so the chain top IS X2, and X1 only appears as X2's issuer. Pinning X1 alone
 *   is enough for OpenSSL, which builds the last hop itself, but the device's
 *   mbedTLS answered "Certificate verification failed" with that single anchor:
 *   on this platform the anchor that actually signs the presented chain works,
 *   the one that signs the anchor does not. That is the reason X2 is the bundle.
 *
 *   WHY X1 IS NOT HERE. X1 was pinned alongside X2 as belt and braces, and the
 *   pair cost this board the one resource it does not have: contiguous DRAM in
 *   the middle of a handshake. X2 is self-signed (subject == issuer) and valid
 *   into 2040, so it is a complete trust anchor on its own - a chain that ends
 *   there never needs X1. Leaving it in only bought one extra parsed certificate
 *   plus an RSA-4096 verification of X2 against X1, and that verification is
 *   exactly what the crash log caught failing with
 *   "BIGNUM - Memory allocation failed". An unused root is not free here.
 *
 *   If verification ever fails with X2 alone, X1 can be restored in one edit: the
 *   block is kept, commented, at the bottom of this file.
 *
 *   Neither root rotates before 2035/2040, so no Let's Encrypt renewal - not the
 *   leaf, not the intermediates, which rotate far more often - can require a
 *   firmware update. The leaf's own dates are checked against the device clock,
 *   which is why FT_NTP is 1 in features.ini.
 *
 *   mbedTLS parses PEM text: keep every line including the delimiters. An earlier
 *   version of this file stripped them and the handshake died with
 *   "X509 - The CRT/CRL/CSR format is invalid, e.g. different type expected".
 *
 *   Source: the Mozilla trust store's copy,
 *   /usr/share/ca-certificates/mozilla/ISRG_Root_X2.crt.
 */

