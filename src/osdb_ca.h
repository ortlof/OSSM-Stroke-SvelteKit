/*
 *   The roots the session archive trusts: both Let's Encrypt roots, and nothing
 *   else.
 *
 *   The endpoint is published through the same central proxy as npn, hermes and
 *   chat.d4rkn3t.de, and that proxy serves Let's Encrypt certificates. The chain
 *   it presents is
 *
 *       osdb.d4rkn3t.de  <-  YE1  <-  Root YE  <-  ISRG Root X2  <-  ISRG Root X1
 *
 *   so the chain top IS X2, and X1 only appears as X2's issuer. Pinning X1 alone
 *   is enough for OpenSSL, which builds the last hop itself, but the device's
 *   mbedTLS answered "Certificate verification failed" with that single anchor:
 *   on this platform the anchor that actually signs the presented chain works,
 *   the one that signs the anchor does not.
 *
 *   Both roots are pinned for that reason, and the pair has a second advantage:
 *   X1 and X2 are valid into 2035 and 2040, so no Let's Encrypt renewal - not the
 *   leaf, not the intermediates, which rotate far more often - can ever require a
 *   firmware update. The leaf's own dates are checked against the device clock,
 *   which is why FT_NTP is 1 in features.ini.
 *
 *   mbedTLS parses PEM text: keep every line including the delimiters. An earlier
 *   version of this file stripped them and the handshake died with
 *   "X509 - The CRT/CRL/CSR format is invalid, e.g. different type expected".
 *
 *   Sources: the Mozilla trust store's copies,
 *   /usr/share/ca-certificates/mozilla/ISRG_Root_X1.crt and _X2.crt.
 */

